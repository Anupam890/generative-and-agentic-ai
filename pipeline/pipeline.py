HISTORY_FILE = os.path.join(os.path.dirname(__file__), "..", "research_history.json")


def save_to_history(topic: str, state: dict):
    history = load_history()
    entry = {
        "topic": topic,
        "timestamp": datetime.now().isoformat(),
        "report": state.get("research_report", state.get("comparison_report", "")),
        "critic_feedback": state.get("critic_feedback", ""),
        "critic_score": state.get("critic_score", 0),
        "fact_check": state.get("fact_check", ""),
    }
    history.append(entry)
    with open(HISTORY_FILE, "w", encoding="utf-8") as f:
        json.dump(history, f, indent=2, ensure_ascii=False)


def load_history() -> list:
    if os.path.exists(HISTORY_FILE):
        with open(HISTORY_FILE, "r", encoding="utf-8") as f:
            return json.load(f)
    return []


