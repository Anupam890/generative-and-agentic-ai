def validate_api_keys(model_name: str = "mistral-small-latest"):
    """Validate that required API keys are set for the chosen model."""
    provider = AVAILABLE_MODELS.get(model_name, "Mistral")
    key_map = {
        "Mistral": "MISTRAL_API_KEY",
        "OpenAI": "OPENAI_API_KEY",
        "Google": "GOOGLE_API_KEY",
    }
    required_key = key_map.get(provider, "MISTRAL_API_KEY")
    if not os.getenv(required_key):
        raise EnvironmentError(f"Missing {required_key} in .env file for {provider} models.")

    if not os.getenv("TAVILY_API_KEY"):
        raise EnvironmentError("Missing TAVILY_API_KEY in .env file (required for web search).")


def export_report_markdown(report: str, filename: str = "research_report.md"):
    with open(filename, "w", encoding="utf-8") as f:
        f.write(report)
    return filename


